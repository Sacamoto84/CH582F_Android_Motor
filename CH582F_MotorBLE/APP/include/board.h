/********************************************************************************
 * board.h — распиновка под WeAct CH57x/CH58x Core Board V1.0 с CH582F
 *
 * Что уже разведено на плате (WeAct-CH57xCH58xCoreBoard_V10_SchDoc.pdf):
 *   PA10/PA11  кварц X1 32.768 кГц ±10ppm  → CLK_OSC32K = 0, пины заняты
 *   X32MI/MO   кварц X2 32 МГц             → обязателен для BLE
 *   пины 3-4   дроссель L1 22 мкГн         → DC-DC разведён, можно включать
 *   PA8        синий LED D2 через R1 5.1к на VDD33 → активный низкий
 *   PB23       кнопка K1 «RST» — вывод сброса, CFG_RESET_EN включён
 *   PB22       кнопка K2 «BOOT» — используем как пользовательскую
 *   PB10/PB11  скорее всего UD-/UD+ на разъём USB-C — не занимать
 *   U2         LDO ME6216A33 → 3.3 В, вход VDD5V (через диод D1 с USB)
 *******************************************************************************/
#ifndef __BOARD_H
#define __BOARD_H

#include "CH58x_common.h"

/* ---------------------------------------------------------------- тактовая */
/* Задаётся один раз в main() через SetSysClock(CLK_SOURCE_PLL_60MHz). */
#define SYS_CLK_HZ              60000000UL

/* ------------------------------------------------- окно для отладчика */
/* Глухая пауза в самом начале main(), как Delay_Ms(5000) в проекте на
 * CH32V003. Нужна потому, что в Shutdown ядро обесточено и отладчик к
 * чипу не цепляется: если прошивка успевает уснуть раньше, чем WCH-Link
 * захватит ядро, залить новую версию можно только через ISP-загрузчик
 * (кнопка BOOT при сбросе).
 *
 * Пауза стоит ДО настройки пинов, поэтому спасает даже когда прошивка
 * падает позже. Цена — столько же миллисекунд до старта рекламы BLE.
 *
 * 0 = выключить. Прошивка заливается через ISP-загрузчик, поэтому пауза
 * не нужна: не уснуть при коротком sleep_tout_s она всё равно не поможет. */
#ifndef BOOT_DELAY_MS
#define BOOT_DELAY_MS           0
#endif

/* ------------------------------------------------- режим дружбы с отладчиком */
/* WCH-Link держит ядро только пока чип жив и не остановлен посторонним
 * сбросом. Три механизма выдёргивают чип из-под отладчика:
 *
 *   1. Сторожевой таймер. На точке останова ядро стоит, а таймер считает
 *      и через 559 мс сбрасывает чип. Отладка становится невозможной.
 *   2. Глубокий сон через sleep_tout_s: ядро обесточивается, WCH-Link
 *      теряет цель насовсем.
 *   3. Детектор просадки VDD33: даёт NMI и сброс, в том числе на бросках
 *      тока при прошивке.
 *
 * DEBUG_FRIENDLY = 1 отключает все три. Ставить 0 в рабочей прошивке —
 * там они нужны, особенно сторожевой таймер против зависаний от просадки. */
#ifndef DEBUG_FRIENDLY
#define DEBUG_FRIENDLY          0
#endif

/* -------------------------------------------------------------------- пины */
/* ШИМ мотора: PWMX, канал PWM9 на PB7.
 *
 * Таймерный ШИМ (26 бит, любая частота) использовать не вышло — все выходы
 * TMR в QFN28 заняты: PA9 отладочный UART, PA10/PA11 кварц 32768,
 * PB22/PB23 кнопки платы, PB10/PB11 линии USB, PA2 в корпусе отсутствует.
 *
 * Следствие: у PWMX счётчик 8 бит и делитель тактовой 8 бит, поэтому
 *      Fmin = Fsys / 255 / 256 = 919 Гц   при Fsys = 60 МГц
 * Буст делается повышенной скважностью, а не пониженной частотой. */
#define MOTOR_PWM_CH            CH_PWM9
#define MOTOR_PWM_PIN           GPIO_Pin_7          /* PB7, пин 14 */
#define MOTOR_PWM_DATA_REG      R8_PWM9_DATA
#define MOTOR_PWM_NCYC          256                 /* PWMX_Cycle_256 */

/* --------------------------------------------------------------------- АЦП */
/* Потенциометр. Питается с PA13 через последовательный резистор 8.2к:
 * без него верх потенциометра сидел бы на 3.3 В, а полезный вход АЦП при
 * PGA 0 дБ — только 0..2.0 В, и верхние 40 % хода ручки упирались бы
 * в потолок. С 8.2к при потенциометре 10к максимум = 3.3*10/18.2 = 1.81 В. */
#define AIN_POT                 CH_EXTIN_2          /* PA12, пин 28 */
#define PIN_POT                 GPIO_Pin_12

/* Напряжение аккумулятора: делитель прямо с BAT+, до LDO, поэтому виден
 * весь разряд 4.2 -> 3.0 В. Ветка обесточивается ключом (см. PIN_VBAT_PWR). */
#define AIN_VBAT                CH_EXTIN_4          /* PA14, пин 26 */
#define PIN_VBAT                GPIO_Pin_14

/* Цифровой вход на аналоговых пинах гасится вручную: GPIOA_ModeCfg() этого
 * не делает. RB_PIN_ADC2_3_IE накрывает PA12+PA13, RB_PIN_ADC4_5_IE —
 * PA14+PA15. PA13 и PA15 у нас цифровые выходы, выключенный приёмник
 * им не мешает. */
#define ANALOG_IE_MASK          (RB_PIN_ADC2_3_IE | RB_PIN_ADC4_5_IE)

/* Прочая периферия */
#define PIN_POT_PWR             GPIO_Pin_13         /* PA13, пин 27 — питание потенциометра */
#define PIN_VBAT_PWR            GPIO_Pin_15         /* PA15, пин 25 — ключ ветки делителя */
#define PIN_KEY                 GPIO_Pin_22         /* PB22, пин 17 — кнопка K2 «BOOT» платы */
#define PIN_LED                 GPIO_Pin_8          /* PA8,  пин 6  — синий LED платы */
#define PIN_DBG_TX              bTXD1               /* PA9,  пин 7  — TXD1 без ремапа */

/* Зуммер. НЕ вешать на PWMX: R8_PWM_CLOCK_DIV и период общие для всех
 * каналов PWM4..PWM11, а канал мотора уже задал свою частоту. Дёргать
 * ножкой из прерывания свободного таймера. */
#define PIN_BUZZER              GPIO_Pin_4          /* PB4, пин 15 */

/* ----------------------------------------------------- свободные ножки
 *
 * После сброса все GPIO — входы без подтяжек. Незанятая ножка «висит»:
 * потенциал входа болтается около порога, оба транзистора приёмника
 * приоткрыты, и через него течёт сквозной ток — единицы микроампер на пин.
 * Против 0.2 мкА всего чипа в Shutdown это на порядки больше, а рядом ещё
 * ключ мотора на 0.7 А, наводки от которого такой вход ловит охотно.
 *
 * Лечится опорой: вход с подтяжкой (тока нет, пока ножка ни к чему не
 * подключена) либо выход в ноль. Подтяжку выбираем как более безопасную —
 * ножки выведены на гребёнку, замыкание выходом на землю было бы коротким.
 *
 * Не трогаем: PB14/PB15 (SWD) и PA10/PA11 (кварц 32768) — это не обычные
 * GPIO; PB10/PB11 — линии USB, через них идёт прошивка по ISP, ножки
 * принадлежат загрузчику и USB-хосту.
 *
 * PB23 — вывод сброса RST#. Опция CFG_RESET_EN включена, снаружи вывод
 * подтянут к 3.3 В, так что это больше не GPIO и настраивать его нечем. */
#define UNUSED_PINS_A_PD        (GPIO_Pin_4 | GPIO_Pin_5)
#define UNUSED_PINS_B_PD        (GPIO_Pin_12 | GPIO_Pin_13)

#define POT_PWR_ON()            GPIOA_SetBits(PIN_POT_PWR)
#define POT_PWR_OFF()           GPIOA_ResetBits(PIN_POT_PWR)

/* Ключ ветки делителя аккумулятора: PA15 → 100к → база BC547, коллектор на
 * затвор P-канального AO3401, исток на BAT+, затвор подтянут к истоку 100к.
 *
 *   PA15 = 1      база 26 мкА, BC547 в насыщении, Vgs ≈ −4 В, ключ открыт
 *   PA15 = вход   BC547 закрыт, затвор подтянут к истоку, ключ закрыт
 *
 * Выключение сделано переводом пина во вход, как задумано в схеме.
 * ОБЯЗАТЕЛЬНО поставить 10к база–эмиттер: висящая база рядом с ШИМ-ключом
 * ловит наводку и может приоткрыть транзистор. С этим резистором вход
 * эквивалентен нулю. */
#define VBAT_PWR_ON()           do { GPIOA_ModeCfg(PIN_VBAT_PWR, GPIO_ModeOut_PP_5mA); \
                                     GPIOA_SetBits(PIN_VBAT_PWR); } while(0)
#define VBAT_PWR_OFF()          GPIOA_ModeCfg(PIN_VBAT_PWR, GPIO_ModeIN_Floating)

/* Масштаб канала аккумулятора.
 * Делитель R1 = 22к (верх) / R2 = 18к (низ), K = 40/18 = 2.2222
 * АЦП при PGA 0 дБ: V = ADC/2048 * Vref, Vref = 1050 мВ
 *   мВ = ADC * (1050/2048) * 2.2222 = ADC * 1.1393
 * В Q12: 1.1393 * 4096 = 4666
 * Значение живёт в настройках (vbat_scale_q12) и калибруется, здесь дефолт.
 *
 * Проверка потолка: 4.2 В → 1.89 В на пине, предел 0 дБ 2.0 В — влезает. */
#define VBAT_SCALE_Q12_DEFAULT  4666


#define ADC_RAW_TO_MV(raw, q12) ((uint16_t)(((uint32_t)(raw) * (uint32_t)(q12)) >> 12))

/* D2 на плате: анод через R1 5.1к на VDD33, катод на PA8 → горит при нуле */
#define LED_ON()                GPIOA_ResetBits(PIN_LED)
#define LED_OFF()               GPIOA_SetBits(PIN_LED)

/* Кнопка K2 замыкает пин на землю */
#define KEY_PRESSED()           (!(GPIOB_ReadPortPin(PIN_KEY)))

/* Флаг прерывания PB22 живёт в бите 8 регистра R16_PB_INT_IF — там же, где
 * PB8 (см. RB_PIN_INTX). Штатный GPIOB_ClearITFlagBit() собирает 32-битное
 * значение 0x400100 и компилятор ругается на усечение при записи в
 * 16-битный регистр. Результат при этом верный, но проще писать нужный
 * бит сразу. */
#define KEY_IT_BIT              ((uint16_t)(PIN_KEY >> 14))     /* PB22 → бит 8 */
#define KEY_CLEAR_IT()          (R16_PB_INT_IF = KEY_IT_BIT)

/* --------------------------------------------------------- частоты ШИМ, Гц */
/* Границы задаёт PWMX: Fout = Fsys / R8_PWM_CLOCK_DIV / 256, делитель 1..255 */
#define MOTOR_PWM_HZ_MIN        (SYS_CLK_HZ / 255 / MOTOR_PWM_NCYC)   /* ~919 Гц  */
#define MOTOR_PWM_HZ_MAX        (SYS_CLK_HZ / 1   / MOTOR_PWM_NCYC)   /* ~234 кГц */

/* -------------------------------------------------------------- плавный пуск
 *
 * Ротор стоит, противо-ЭДС нет, обмотка — просто 2 Ома. Скачок скважности
 * сразу на рабочую даёт ток около V/R, у нас это ~1.6 А против 0.7 А в работе.
 * На внутреннем сопротивлении банки и разъёмов это роняло питание почти
 * на полвольта.
 *
 * Лечится тем, что ток идёт следом за скважностью: наращиваем её от
 * MOTOR_SOFT_START_PM до полной за MOTOR_SOFT_START_MS, и бросок срезается
 * во столько же раз. Как только ротор тронулся, появляется противо-ЭДС
 * и ток падает сам.
 *
 * Потолок действует на ЛЮБУЮ скважность в этом окне, включая рывок: он
 * упирается в потолок, пока тот не дорастёт до boost_power.
 *
 * MOTOR_SOFT_START_MS = 0 выключает плавный пуск. */
#define MOTOR_SOFT_START_MS     60      /* за сколько выйти на полную      */
#define MOTOR_SOFT_START_PM     250     /* с какой скважности начинать, ‰  */

#endif /* __BOARD_H */
